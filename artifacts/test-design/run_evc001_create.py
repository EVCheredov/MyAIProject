def build_desc(preconds, steps, expected):
    parts = []
    if preconds:
        parts.append("## Предусловия")
        for i, x in enumerate(preconds, 1):
            parts.append(f"{i}. {x}")
        parts.append("")
    parts.append("## Шаги")
    for i, x in enumerate(steps, 1):
        parts.append(f"{i}. {x}")
    parts.append("")
    parts.append("## Ожидаемый результат")
    parts.append(f"- {expected}")
    parts.append("")
    parts.append("## Тестовые данные")
    parts.append("- MSISDN +79991112233 / +79991112244; пароль SuperGsm2024")
    return "\n".join(parts)


def main():
    results = []
    for title, preconds, steps, expected in TESTS:
        desc = build_desc(preconds, steps, expected)
        try:
            r = tc.create_test(suite_id=SUITE_ID, title=title, desc=desc)
            results.append({
                "title": title,
                "id": r.get("test_id"),
                "url": r.get("url"),
                "status": "success",
            })
            print(f"[OK] {r.get('test_id')}  {title}")
        except Exception as e:  # noqa: BLE001
            results.append({"title": title, "status": "error", "error": str(e)})
            print(f"[FAIL] {title}: {e}")

    out_path = PROJECT_ROOT / "artifacts" / "test-design" / "create_evc001_v4.result.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    ok = sum(1 for r in results if r["status"] == "success")
    print(f"\n===== ИТОГ: создано {ok} / {len(results)} =====")
    print(f"Результат: {out_path}")


if __name__ == "__main__":
    main()
