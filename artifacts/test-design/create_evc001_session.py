def main():
    results = []
    for c in CASES:
        try:
            r = tc.create_test(suite_id=SUITE_ID, title=c["t"], desc=c["desc"])
            r["_success"] = True
        except Exception as e:  # noqa: BLE001
            r = {"status": "error", "title": c["t"], "error": str(e), "_success": False}
        results.append(r)
        mark = "OK " if r.get("_success") else "ERR"
        print(f"{mark} {c['t'][:60]:60s} -> {r.get('test_id') or r.get('error')}")
    out = ROOT / "artifacts" / "test-design" / "create_evc001_session.result.json"
    out.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    ok = sum(1 for r in results if r.get("_success"))
    print(f"\nCreated {ok}/{len(CASES)}. Result file: {out}")

if __name__ == "__main__":
    main()
